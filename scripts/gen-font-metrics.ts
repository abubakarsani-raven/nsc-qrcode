/**
 * Emit src/lib/id-card/font-metrics.generated.ts — advance widths and ink
 * extents for every card font, so the browser preview and the print PDF lay
 * text out from the same numbers (no DOM measuring, no guessed em widths).
 *
 *   npx tsx scripts/gen-font-metrics.ts
 */
import fs from "fs/promises";
import path from "path";
import fontkit from "@pdf-lib/fontkit";

const FONTS = {
  "poppins-regular": "Poppins-Regular.ttf",
  "poppins-bold": "Poppins-Bold.ttf",
  "inter-display-regular": "InterDisplay-Regular.ttf",
  "inter-display-extrabold": "InterDisplay-ExtraBold.ttf",
} as const;

function codepoints() {
  const out: number[] = [];
  for (let cp = 0x20; cp <= 0x7e; cp++) out.push(cp);
  for (let cp = 0xa0; cp <= 0x17f; cp++) out.push(cp);
  out.push(0x2018, 0x2019, 0x201c, 0x201d, 0x2013, 0x2014);
  return out;
}

async function main() {
  const root = process.cwd();
  const blocks: string[] = [];
  for (const [id, file] of Object.entries(FONTS)) {
    const bytes = await fs.readFile(path.join(root, "public", "fonts", file));
    const font = fontkit.create(bytes);
    const glyphs: Record<string, [number, number, number]> = {};
    for (const cp of codepoints()) {
      if (!font.hasGlyphForCodePoint(cp)) continue;
      const g = font.glyphForCodePoint(cp);
      const bbox = g.bbox;
      const empty = !Number.isFinite(bbox.minX) || bbox.maxX <= bbox.minX;
      glyphs[String.fromCodePoint(cp)] = [
        Math.round(g.advanceWidth),
        empty ? 0 : Math.round(bbox.minX),
        empty ? 0 : Math.round(bbox.maxX),
      ];
    }
    blocks.push(
      `  ${JSON.stringify(id)}: {\n` +
        `    unitsPerEm: ${font.unitsPerEm},\n` +
        `    ascender: ${font.ascent},\n` +
        `    descender: ${font.descent},\n` +
        `    capHeight: ${font.capHeight},\n` +
        `    glyphs: ${JSON.stringify(glyphs)},\n` +
        `  },`,
    );
  }

  const out = `/**
 * Generated by scripts/gen-font-metrics.ts — do not edit by hand.
 * glyphs: char -> [advance, inkMinX, inkMaxX] in font units.
 */

export type CardFontId = ${Object.keys(FONTS)
    .map((k) => JSON.stringify(k))
    .join(" | ")};

export type FontMetrics = {
  unitsPerEm: number;
  ascender: number;
  descender: number;
  capHeight: number;
  glyphs: Record<string, [number, number, number]>;
};

export const FONT_FILES: Record<CardFontId, string> = ${JSON.stringify(FONTS, null, 2)};

export const FONT_METRICS: Record<CardFontId, FontMetrics> = {
${blocks.join("\n")}
};
`;
  const target = path.join(root, "src", "lib", "id-card", "font-metrics.generated.ts");
  await fs.writeFile(target, out);
  console.log("Wrote", target, `(${(out.length / 1024).toFixed(1)} KB)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
